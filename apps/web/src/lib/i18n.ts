export function translateText(value: string, language: AppLanguage): string {
  if (language === "fr" || !value.trim()) return value;
  let translated = value;
  for (const [source, target] of translations) {
    translated = translated.split(source).join(target);
  }
  return translated;
}

export function translateAttribute(value: string | null, language: AppLanguage): string | null {
  return value === null ? null : translateText(value, language);
}
